#include <iostream>
using namespace std;

int main()
{
    int a = 100, b = 2;

    cout << "Addition: " << a + b << "\n";
    cout << "Subtraction: " << a - b << "\n";
    cout << "Multiplication: " << a * b << "\n";
    cout << "Division: " << a / b << "\n";
    cout << "Modulus: " << a % b << "\n";
}