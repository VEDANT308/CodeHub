#include <iostream>
using namespace std;

int main() {
    int integerValue = 42;
    double doubleValue = 3.14;
    char charValue = 'A';
    bool boolValue = true;
    long longValue = 1234567890;
    float floatValue = 2.718f;


    cout << "Integer Value: " << integerValue << endl;
    cout << "Double Value: " << doubleValue << endl;    
    cout << "Character Value: " << charValue << endl;
    cout << "Boolean Value: " << boolValue << endl;
    cout << "Long Value: " << longValue << endl;
    cout << "Float Value: " << floatValue << endl;
    
    return 0;
}